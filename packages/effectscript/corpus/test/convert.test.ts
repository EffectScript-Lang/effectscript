import {
  convertRepo,
  convertRepoParallel,
  elide,
  report,
  summarize,
  writeSideBySide
} from "@effectscript/corpus/convert"
import { primary } from "@effectscript/tokens"
import { spawnSync } from "node:child_process"
import * as fs from "node:fs"
import * as os from "node:os"
import * as path from "node:path"
import { describe, expect, it } from "vitest"

const project = () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "efx-corpus-"))
  const write = (file: string, text: string) => {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true })
    fs.writeFileSync(path.join(dir, file), text)
  }
  write(
    "src/users.ts",
    "import { Effect } from \"effect\"\n\nexport const greet = Effect.fn(\"greet\")(function*(name: string) {\n  yield* Effect.log(name)\n  return name\n})\n"
  )
  write(
    "src/gen.ts",
    "// @generated by a tool\nimport { Effect } from \"effect\"\nexport const x = Effect.succeed(1)\n"
  )
  write("src/plain.ts", "export const add = (a: number, b: number) => a + b\n")
  write("src/types.d.ts", "declare const x: number\n")
  write("node_modules/dep/index.ts", "import { Effect } from \"effect\"\n")
  write(".repos/effect/src/Effect.ts", "import { Effect } from \"effect\"\n")
  const git = (...args: Array<string>) =>
    spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd: dir, encoding: "utf8" })
  git("init", "-q")
  git("add", "-A", "-f")
  git("commit", "-qm", "init")
  return dir
}

describe("the corpus converter (ADR-0094)", () => {
  it("converts the Effect files and sets generated and plain files apart", () => {
    const repo = convertRepo(project(), "demo")
    expect(repo.commit).toMatch(/^[0-9a-f]{40}$/)
    expect(repo.files.map((f) => [f.path, f.effect, f.generated, f.changed])).toEqual([
      ["src/gen.ts", true, true, false],
      ["src/plain.ts", false, false, false],
      ["src/users.ts", true, false, true]
    ])
    const users = repo.files.find((f) => f.path === "src/users.ts")!
    expect(users.efx).toContain("export effect greet(name: string) {\n  console.log(name)\n  return name\n}\n")
  })

  it("converts the same in parallel, in the same order", async () => {
    const dir = project()
    const parallel = await convertRepoParallel(dir, "demo", { jobs: 3 })
    expect(parallel).toEqual(convertRepo(dir, "demo"))
  }, 60_000)

  it("leaves out what a project's exclusions name", () => {
    const repo = convertRepo(project(), "demo", { exclude: ["src/gen.*"] })
    expect(repo.files.map((f) => f.path)).toEqual(["src/plain.ts", "src/users.ts"])
  })

  it("writes each converted file next to its TypeScript", () => {
    const repo = convertRepo(project(), "demo")
    const out = fs.mkdtempSync(path.join(os.tmpdir(), "efx-corpus-out-"))
    writeSideBySide(out, repo)
    expect(fs.readdirSync(path.join(out, "demo/src")).sort()).toEqual(["users.efx", "users.ts"])
  })

  it("reports numbers and elided notes, never code", async () => {
    const summary = await summarize(convertRepo(project(), "demo"), [primary])
    expect([summary.effectFiles, summary.converted, summary.generated]).toEqual([1, 1, 1])
    expect(summary.tokens.o200k!.efx).toBeLessThan(summary.tokens.o200k!.ts)
    const markdown = report([{ ...summary, notes: { [elide("`Users` stays TypeScript: its `size` field")]: 2 } }], [
      primary
    ])
    expect(markdown).toContain("| demo |")
    expect(markdown).toContain("| 2 | 1 | `…` stays TypeScript: its `…` field |")
    expect(markdown).not.toContain("greet")
    expect(elide("`x` stays TypeScript: its span name \"Users.find\" differs")).toBe(
      "`…` stays TypeScript: its span name \"…\" differs"
    )
  }, 120_000)
})
